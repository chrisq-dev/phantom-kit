// Returns vendor name from MAC first 3 bytes, or "Desconocido"
static inline String lookupOUI(const uint8_t mac[3]) {
    for (size_t i = 0; i < OUI_TABLE_SIZE; i++) {
        uint8_t p0 = pgm_read_byte(&OUI_TABLE[i].prefix[0]);
        uint8_t p1 = pgm_read_byte(&OUI_TABLE[i].prefix[1]);
        uint8_t p2 = pgm_read_byte(&OUI_TABLE[i].prefix[2]);
        if (mac[0] == p0 && mac[1] == p1 && mac[2] == p2) {
            char buf[20];
            strncpy_P(buf, OUI_TABLE[i].vendor, sizeof(buf));
            buf[sizeof(buf) - 1] = '\0';
            return String(buf);
        }
    }
    return "Desconocido";
}

